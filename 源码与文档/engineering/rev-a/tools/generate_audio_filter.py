#!/usr/bin/env python3
"""63 tap Blackman windowed sinc, 6.5 kHz cutoff; 48 kHz -> 16 kHz."""
from pathlib import Path
import math
root=Path(__file__).resolve().parents[1]
h=[]
for i in range(63):
    x=i-31;fc=6500/48000
    v=2*fc if x==0 else math.sin(2*math.pi*fc*x)/(math.pi*x)
    h.append(v*(.42-.5*math.cos(2*math.pi*i/62)+.08*math.cos(4*math.pi*i/62)))
h=[x/sum(h) for x in h]
(root/'firmware/core/audio_coefficients.h').write_text('/* Generated by tools/generate_audio_filter.py. */\nstatic const float coefficients[63]={\n'+',\n'.join(f'{x:.11g}f' if x != 0 else '0.0f' for x in h)+'\n};\n')
